  t(key) {
    const lang = this.translations[this.currentLang] || this.translations.en;
    return lang[key] || this.translations.en[key] || key;
  },

  setLanguage(langCode) {
    if (this.translations[langCode]) {
      this.currentLang = langCode;
      localStorage.setItem("medisync_lang", langCode);
      this.applyTranslations();
    }
  },

  applyTranslations() {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const val = this.t(key);
      if (val) {
        if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
          // Keep input taking patterns in English as instructed
          return;
        }
        if (el.children.length === 0) {
          el.textContent = val;
        } else {
          const textTarget = el.querySelector(".i18n-text") || el.querySelector("span:not([class*='icon']):last-child");
          if (textTarget) {
            textTarget.textContent = val;
          } else {
            el.childNodes.forEach((node) => {
              if (node.nodeType === Node.TEXT_NODE && node.textContent.trim().length > 0) {
                node.textContent = val;
              }
            });
          }
        }
      }
    });

    // Update html lang attribute
    document.documentElement.lang = this.currentLang;
  }
