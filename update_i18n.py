for lang, keys_dict in new_keys.items():
    # Find lang block: e.g. "en: {"
    marker = f"{lang}: {{"
    pos = content.find(marker)
    if pos != -1:
        # Build JS string of keys
        js_entries = []
        for k, v in keys_dict.items():
            # escape double quotes
            safe_v = v.replace('"', '\\"').replace('\n', '\\n')
            js_entries.append(f'      {k}: "{safe_v}",')
        keys_str = "\n" + "\n".join(js_entries) + "\n"
        insert_pos = pos + len(marker)
        content = content[:insert_pos] + keys_str + content[insert_pos:]

with open("frontend/i18n.js", "w", encoding="utf-8") as f:
    f.write(content)

